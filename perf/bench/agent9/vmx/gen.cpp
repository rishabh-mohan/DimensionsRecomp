// gen.cpp - VMX fallback proof, step 1 (emitted text).
//
// Compiles the ORIGINAL emitters (orig_emitters.inc, copied out of vector.cpp before it was edited;
// SHA256 of that vector.cpp: B3528ED4A7E0642E2F390CF3D745E18D6E496F14D1707AFEF6F7049BB84FB39D)
// and the NEW ones (new_emitters.inc, extracted from the edited vector.cpp by extract.ps1) against
// a fake BuilderContext. For every op and operand pattern it:
//   1. checks that the new emitter with vmxVectorFallbacks=false prints exactly the old text;
//   2. checks the flag-on alias rule: every new form is the distinct-operand text renamed, except
//      vpkuhus/vpkuwus, which keep the scalar text when vD is vA or vB;
//   3. writes three kernels per (op, pattern) into gen_out/kernels.inc for harness.cpp: the old
//      text (k_*_old), the flag-on text (k_*_new) and the distinct-operand SSE text renamed to the
//      pattern's registers (k_*_sse, used to show the vpku*us scalar text is wrong under aliasing);
//   4. writes all texts to gen_out/emitted.txt.
// Exit code = number of failed checks.
#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <filesystem>
#include <format>
#include <fstream>
#include <iterator>
#include <string>
#include <string_view>
#include <utility>

namespace fake {
struct RecompilerConfig {
  bool vmxVectorFallbacks = false;
};
struct Instruction {
  uint32_t operands[4] = {};
};
// Only the members the emitters use, with the real return types (v() returns std::string, temp()
// returns const char*). println appends one formatted line, like the real one.
struct BuilderContext {
  RecompilerConfig cfg;
  Instruction insn;
  std::string out;
  const RecompilerConfig& config() const { return cfg; }
  std::string v(size_t index) { return std::format("ctx.v{}", index); }
  const char* temp() { return "temp"; }
  template <typename... Args>
  void println(std::format_string<Args...> f, Args&&... args) {
    out += std::format(f, std::forward<Args>(args)...);
    out += '\n';
  }
};
}  // namespace fake

namespace orig {
using fake::BuilderContext;
#include "orig_emitters.inc"
}  // namespace orig

namespace neu {
using fake::BuilderContext;
#include "new_emitters.inc"
}  // namespace neu

using Emitter = bool (*)(fake::BuilderContext&);
struct Op {
  const char* name;
  Emitter old_fn;
  Emitter new_fn;
};
#define OP(n) Op{#n, &orig::build_##n, &neu::build_##n}
static const Op kOps[] = {OP(vsubsws), OP(vsrb), OP(vsrab),   OP(vrlw),
                          OP(vsraw),   OP(vsrw), OP(vpkuhus), OP(vpkuwus)};

struct Pattern {
  const char* name;
  uint32_t d, a, b;
};
static const Pattern kPatterns[] = {{"distinct", 3, 1, 2},
                                    {"d_eq_a", 1, 1, 2},
                                    {"d_eq_b", 2, 1, 2},
                                    {"a_eq_b", 3, 1, 1},
                                    {"all_eq", 1, 1, 1}};

static std::string emit(Emitter fn, const Pattern& p, bool flag) {
  fake::BuilderContext ctx;
  ctx.cfg.vmxVectorFallbacks = flag;
  ctx.insn.operands[0] = p.d;
  ctx.insn.operands[1] = p.a;
  ctx.insn.operands[2] = p.b;
  if (!fn(ctx)) ctx.out += "#error emitter returned false\n";
  return ctx.out;
}

static std::string replace_all(std::string s, std::string_view from, std::string_view to) {
  for (size_t pos = 0; (pos = s.find(from, pos)) != std::string::npos; pos += to.size())
    s.replace(pos, from.size(), to);
  return s;
}

// The distinct-operand text (vD=v3, vA=v1, vB=v2) with the registers of pattern p.
static std::string rename(const std::string& t, const Pattern& p) {
  std::string s =
      replace_all(replace_all(replace_all(t, "ctx.v3", "@D"), "ctx.v1", "@A"), "ctx.v2", "@B");
  s = replace_all(s, "@D", std::format("ctx.v{}", p.d));
  s = replace_all(s, "@A", std::format("ctx.v{}", p.a));
  return replace_all(s, "@B", std::format("ctx.v{}", p.b));
}

static std::string kernel(const std::string& name, const std::string& body) {
  return std::format("REX_KERNEL({}) {{\n\t[[maybe_unused]] PPCRegister temp;\n{}}}\n\n", name,
                     body);
}

static size_t lines(const std::string& s) { return size_t(std::count(s.begin(), s.end(), '\n')); }

int main() {
  std::filesystem::create_directories("gen_out");
  std::string kernels = "// Generated by gen.exe (bench/agent9/vmx). Do not edit.\n\n";
  std::string table = "static const KernelInfo kKernels[] = {\n";
  std::string dump;
  int off_mismatch = 0, alias_rule_mismatch = 0;
  std::printf("%-8s %-9s %-24s %s\n", "op", "pattern", "flag off vs original", "flag on");
  for (const Op& op : kOps) {
    const std::string distinct_on = emit(op.new_fn, kPatterns[0], true);
    const bool vpku = std::string_view(op.name).starts_with("vpku");
    for (const Pattern& p : kPatterns) {
      const std::string old_t = emit(op.old_fn, p, false);
      const std::string off_t = emit(op.new_fn, p, false);
      const std::string on_t = emit(op.new_fn, p, true);
      const std::string sse_t = rename(distinct_on, p);
      const bool same = old_t == off_t;
      off_mismatch += !same;
      const bool scalar_kept = on_t == old_t;
      const bool expect_scalar = vpku && (p.d == p.a || p.d == p.b);
      alias_rule_mismatch += expect_scalar ? !scalar_kept : on_t != sse_t;
      const std::string off_s =
          same ? std::format("identical ({} lines)", lines(old_t)) : std::string("DIFFERENT");
      const std::string on_s = scalar_kept ? std::string("scalar text kept")
                                           : std::format("SSE form ({} lines)", lines(on_t));
      std::printf("%-8s %-9s %-24s %s\n", op.name, p.name, off_s.c_str(), on_s.c_str());

      const std::string base = std::format("{}_{}", op.name, p.name);
      kernels += kernel("k_" + base + "_old", old_t);
      kernels += kernel("k_" + base + "_new", on_t);
      kernels += kernel("k_" + base + "_sse", sse_t);
      table += std::format("    {{\"{}\", \"{}\", {}, {}, {}, &k_{}_old, &k_{}_new, &k_{}_sse}},\n",
                           op.name, p.name, p.d, p.a, p.b, base, base, base);
      dump += std::format(
          "==== {} {} (vD=v{} vA=v{} vB=v{}) ====\n-- old (identical to new with the flag off) "
          "--\n{}-- new, vmx_vector_fallbacks = true --\n{}\n",
          op.name, p.name, p.d, p.a, p.b, old_t, on_t);
    }
  }
  table += "};\n";
  std::ofstream("gen_out/kernels.inc", std::ios::binary) << kernels << table;
  std::ofstream("gen_out/emitted.txt", std::ios::binary) << dump;
  std::printf("flag-off text different from the original: %d of %zu\n", off_mismatch,
              std::size(kOps) * std::size(kPatterns));
  std::printf("flag-on text breaking the alias rule: %d\n", alias_rule_mismatch);
  return off_mismatch + alias_rule_mismatch;
}
