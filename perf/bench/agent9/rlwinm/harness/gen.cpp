// Generates the equivalence-test sources. "old" text = the generic emitter format
// strings copied verbatim from logical.cpp (flag off); "new" text = what the flag-on
// builders print: "\t" + rlw::lowerX(...), or the generic text when lowerX declines.
// Usage: gen.exe <outdir> [parts]
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <filesystem>
#include <fstream>
#include <string>
#include <string_view>

#include <fmt/format.h>

#include "rotate_mask.h"

using namespace rex::codegen;

// Verbatim copy of helpers.h compute_mask.
inline uint64_t compute_mask(uint32_t mstart, uint32_t mstop) {
  mstart &= 0x3F;
  mstop &= 0x3F;
  uint64_t value = (UINT64_MAX >> mstart) ^ ((mstop >= 63) ? 0 : UINT64_MAX >> (mstop + 1));
  return mstart <= mstop ? value : ~value;
}

static std::string oldRlwinm(std::string_view ra, std::string_view rs, uint32_t sh, uint32_t mb,
                             uint32_t me) {
  return fmt::format("\t{}.u64 = __builtin_rotateleft64({}.u32 | ({}.u64 << 32), {}) & 0x{:X};",
                     ra, rs, rs, sh, compute_mask(mb + 32, me + 32));
}
static std::string oldRlwimi(std::string_view ra, std::string_view rs, uint32_t sh, uint32_t mb,
                             uint32_t me) {
  const uint64_t mask = compute_mask(mb + 32, me + 32);
  return fmt::format(
      "\t{}.u64 = (__builtin_rotateleft64({}.u32 | ({}.u64 << 32), {}) & 0x{:X}) | ({}.u64 & "
      "0x{:X});",
      ra, rs, rs, sh, mask, ra, ~mask);
}
static std::string oldRlwnm(std::string_view ra, std::string_view rs, std::string_view rb,
                            uint32_t mb, uint32_t me) {
  return fmt::format(
      "\t{}.u64 = __builtin_rotateleft64({}.u32 | ({}.u64 << 32), {}.u8 & 0x1F) & 0x{:X};", ra, rs,
      rs, rb, compute_mask(mb + 32, me + 32));
}
static std::string newRlwinm(std::string_view ra, std::string_view rs, uint32_t sh, uint32_t mb,
                             uint32_t me) {
  auto s = rlw::lowerRlwinm(ra, rs, sh, mb, me);
  return s ? "\t" + *s : oldRlwinm(ra, rs, sh, mb, me);
}
static std::string newRlwimi(std::string_view ra, std::string_view rs, uint32_t sh, uint32_t mb,
                             uint32_t me) {
  auto s = rlw::lowerRlwimi(ra, rs, sh, mb, me);
  return s ? "\t" + *s : oldRlwimi(ra, rs, sh, mb, me);
}
static std::string newRlwnm(std::string_view ra, std::string_view rs, std::string_view rb,
                            uint32_t mb, uint32_t me) {
  auto s = rlw::lowerRlwnm(ra, rs, rb, mb, me);
  return s ? "\t" + *s : oldRlwnm(ra, rs, rb, mb, me);
}
// Alternative rlwimi form measured in the x64 table only (not used by the lowering).
static std::string xorRlwimi(std::string_view ra, std::string_view rs, uint32_t sh, uint32_t mb,
                             uint32_t me) {
  const rlw::Form f = rlw::classify(sh, mb, me);
  return fmt::format("\t{}.u64 ^= (({}) ^ {}.u32) & {};", ra, rlw::rotMaskExpr(rs, sh, mb, me, f),
                     ra, rlw::hexLiteral(rlw::mask32(mb, me)));
}

static_assert(rlw::classify(4, 0, 27) == rlw::Form::kShiftLeft);         // slwi 4
static_assert(rlw::classify(24, 8, 31) == rlw::Form::kShiftRight);       // srwi 8
static_assert(rlw::classify(0, 0, 27) == rlw::Form::kMask);              // clrrwi 4
static_assert(rlw::classify(29, 28, 31) == rlw::Form::kShiftRightMask);  // extrwi 4,25
static_assert(rlw::classify(2, 20, 29) == rlw::Form::kShiftLeftMask);
static_assert(rlw::classify(8, 16, 27) == rlw::Form::kRotateMask);
static_assert(rlw::classify(8, 0, 31) == rlw::Form::kRotate);
static_assert(rlw::classify(0, 0, 31) == rlw::Form::kCopy);
static_assert(rlw::classify(8, 28, 3) == rlw::Form::kNone);  // wrapping mask

static const char* const kFormNames[] = {"none(wrap)",   "copy",       "mask",
                                         "shl",          "shl+mask",   "shr",
                                         "shr+mask",     "rotate",     "rotate+mask"};

static void writeFile(const std::filesystem::path& p, const std::string& text) {
  std::ofstream o(p, std::ios::binary);
  o << text;
  if (!o) {
    std::fprintf(stderr, "gen: cannot write %s\n", p.string().c_str());
    std::exit(1);
  }
}

int main(int argc, char** argv) {
  const std::filesystem::path out = argc > 1 ? argv[1] : "gen";
  const int parts = argc > 2 ? std::atoi(argv[2]) : 4;
  if (parts < 1 || 32 % parts != 0) {
    std::fprintf(stderr, "gen: parts must divide 32\n");
    return 2;
  }
  std::filesystem::create_directories(out);
  std::string summary;
  std::string tables = "// generated by harness/gen.cpp\n#pragma once\n#include \"types.h\"\n";
  tables += fmt::format("constexpr int kParts = {};\nconstexpr int kPerPart = {};\n", parts,
                        32 / parts * 1024);

  for (int kind = 0; kind < 2; ++kind) {
    const char* name = kind == 0 ? "rlwinm" : "rlwimi";
    const char* tname = kind == 0 ? "kRlwinm" : "kRlwimi";
    uint64_t formCount[9] = {}, lowered = 0, funcs = 0;
    std::string list;
    for (int p = 0; p < parts; ++p) {
      std::string body, table;
      int idx = 0;
      for (uint32_t sh = p * 32 / parts; sh < uint32_t(p + 1) * 32 / parts; ++sh) {
        for (uint32_t mb = 0; mb < 32; ++mb) {
          for (uint32_t me = 0; me < 32; ++me, ++idx) {
            const std::string o = kind == 0 ? oldRlwinm("ra", "rs", sh, mb, me)
                                            : oldRlwimi("ra", "rs", sh, mb, me);
            const std::string n = kind == 0 ? newRlwinm("ra", "rs", sh, mb, me)
                                            : newRlwimi("ra", "rs", sh, mb, me);
            const auto form = rlw::classify(sh, mb, me);
            ++formCount[int(form)];
            body += fmt::format("void o{}(Reg& ra, Reg& rs) {{\n{}\n}}\n", idx, o);
            ++funcs;
            std::string nf = fmt::format("o{}", idx);
            if (n != o) {
              body += fmt::format("void n{}(Reg& ra, Reg& rs) {{\n{}\n}}\n", idx, n);
              nf = fmt::format("n{}", idx);
              ++lowered;
              ++funcs;
            }
            table += fmt::format("  {{{}, {}, {}, {}, o{}, {}}},\n", sh, mb, me, int(form), idx, nf);
          }
        }
      }
      writeFile(out / fmt::format("cases_{}_{}.cpp", name, p),
                fmt::format("// generated by harness/gen.cpp\n#include \"types.h\"\nnamespace {{\n{}}}"
                            "  // namespace\nextern const Case2 {}_{}[] = {{\n{}}};\n",
                            body, tname, p, table));
      tables += fmt::format("extern const Case2 {}_{}[];\n", tname, p);
      list += fmt::format("{}{}_{}", p ? ", " : "", tname, p);
    }
    tables += fmt::format("inline const Case2* const {}Parts[] = {{{}}};\n", tname, list);
    summary += fmt::format("{}: 32768 cases, {} lowered, {} functions\n", name, lowered, funcs);
    for (int f = 0; f < 9; ++f)
      summary += fmt::format("  {:<12} {}\n", kFormNames[f], formCount[f]);
  }

  {  // rlwnm
    std::string body, table;
    uint64_t lowered = 0;
    int idx = 0;
    for (uint32_t mb = 0; mb < 32; ++mb) {
      for (uint32_t me = 0; me < 32; ++me, ++idx) {
        const std::string o = oldRlwnm("ra", "rs", "rb", mb, me);
        const std::string n = newRlwnm("ra", "rs", "rb", mb, me);
        int form = 0;
        body += fmt::format("void o{}(Reg& ra, Reg& rs, Reg& rb) {{\n{}\n}}\n", idx, o);
        std::string nf = fmt::format("o{}", idx);
        if (n != o) {
          body += fmt::format("void n{}(Reg& ra, Reg& rs, Reg& rb) {{\n{}\n}}\n", idx, n);
          nf = fmt::format("n{}", idx);
          ++lowered;
          form = rlw::mask32(mb, me) == 0xFFFFFFFFu ? int(rlw::Form::kRotate)
                                                    : int(rlw::Form::kRotateMask);
        }
        table += fmt::format("  {{{}, {}, {}, o{}, {}}},\n", mb, me, form, idx, nf);
      }
    }
    writeFile(out / "cases_rlwnm.cpp",
              fmt::format("// generated by harness/gen.cpp\n#include \"types.h\"\nnamespace {{\n{}}}"
                          "  // namespace\nextern const Case3 kRlwnm[] = {{\n{}}};\n",
                          body, table));
    tables += "extern const Case3 kRlwnm[];\nconstexpr int kRlwnmCount = 1024;\n";
    summary += fmt::format("rlwnm: 1024 cases, {} lowered\n", lowered);
  }
  writeFile(out / "tables.h", tables);

  {  // x64 comparison forms: v_* = registers in locals, c_* = registers in a context struct
    struct X {
      const char* name;
      int kind;  // 0 rlwinm, 1 rlwimi, 2 rlwnm
      uint32_t sh, mb, me;
    };
    static const X kForms[] = {
        {"slwi_4", 0, 4, 0, 27},          {"srwi_8", 0, 24, 8, 31},
        {"clrrwi_4", 0, 0, 0, 27},        {"extrwi_4_25", 0, 29, 28, 31},
        {"shlmask_2_20_29", 0, 2, 20, 29}, {"rotmask_8_16_27", 0, 8, 16, 27},
        {"rlwimi_2_0_29", 1, 2, 0, 29},   {"inslwi_8_16", 1, 16, 16, 23},
        {"insrwi_8_16", 1, 8, 16, 23},    {"rlwimi_8_16_27", 1, 8, 16, 27},
        {"rlwnm_16_27", 2, 0, 16, 27},    {"rlwnm_8_31", 2, 0, 8, 31},
    };
    std::string s =
        "// generated by harness/gen.cpp\n#include <cstdint>\n#include \"types.h\"\n"
        "struct Ctx { Reg r3, r4, r5; };\n";
    std::string order;
    for (const X& f : kForms) {
      for (int v = 0; v < 3; ++v) {  // 0 old, 1 new, 2 xor (rlwimi only)
        if (v == 2 && f.kind != 1)
          continue;
        const char* tag = v == 0 ? "old" : v == 1 ? "new" : "xor";
        for (int ctxMode = 0; ctxMode < 2; ++ctxMode) {
          const char* ra = ctxMode ? "ctx.r3" : "ra";
          const char* rs = ctxMode ? "ctx.r4" : "rs";
          const char* rb = ctxMode ? "ctx.r5" : "rb";
          std::string text;
          if (f.kind == 0)
            text = v == 0 ? oldRlwinm(ra, rs, f.sh, f.mb, f.me) : newRlwinm(ra, rs, f.sh, f.mb, f.me);
          else if (f.kind == 1)
            text = v == 0   ? oldRlwimi(ra, rs, f.sh, f.mb, f.me)
                   : v == 1 ? newRlwimi(ra, rs, f.sh, f.mb, f.me)
                            : xorRlwimi(ra, rs, f.sh, f.mb, f.me);
          else
            text = v == 0 ? oldRlwnm(ra, rs, rb, f.mb, f.me) : newRlwnm(ra, rs, rb, f.mb, f.me);
          if (ctxMode)
            s += fmt::format("extern \"C\" void c_{}_{}(Ctx& ctx) {{\n{}\n}}\n", tag, f.name, text);
          else
            s += fmt::format(
                "extern \"C\" uint64_t v_{}_{}(uint64_t a, uint64_t s, uint64_t b) {{\n"
                "\tReg ra, rs, rb;\n\tra.u64 = a;\n\trs.u64 = s;\n\trb.u64 = b;\n{}\n"
                "\treturn ra.u64;\n}}\n",
                tag, f.name, text);
          summary += fmt::format("x64 {}_{}_{}: {}\n", ctxMode ? "c" : "v", tag, f.name,
                                 text.substr(1));
        }
      }
      order += fmt::format("{}\n", f.name);
    }
    writeFile(out / "x64_forms.cpp", s);
    writeFile(out / "x64_order.txt", order);
  }
  writeFile(out / "summary.txt", summary);
  std::fputs(summary.c_str(), stdout);
  return 0;
}
