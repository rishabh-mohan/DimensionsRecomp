<#
.SYNOPSIS
  Builds and runs Agent 8's session-2 journal and HexWords benches.

.DESCRIPTION
  journal  : bench/agent8/journal/journal_bench.cpp. It compiles the real
             DimensionsRecomp/rexlego/src/native_heap_journal.h against the
             session-1 copy bench/agent8/journal/journal_old.h.
  hexwords : bench/agent8/hexwords/hexwords_bench.cpp. HexWords is extracted
             verbatim from build/agent8/orig/native_skin_diagnostics.cpp (old)
             and DimensionsRecomp/rexlego/src/native_skin_diagnostics.cpp (new).

  Flags match the game build (clang++ -O3 -std=gnu++23 -msse4.1
  -march=x86-64-v3, dynamic CRT). Each compile is a single process and each
  bench uses at most 2 threads. Binaries go to build/agent8/{journal,hexwords};
  results, with a CPU-load snapshot taken before and after, are appended to
  bench/agent8/{journal,hexwords}/results.txt.

.EXAMPLE
  powershell -NoProfile -File bench\agent8\build-journal-hexwords.ps1            # 7 runs
  powershell -NoProfile -File bench\agent8\build-journal-hexwords.ps1 -Quick     # smoke test
#>
param(
  [int]$Runs = 7,
  [switch]$Quick,
  [switch]$NoRun,
  [ValidateSet('all', 'journal', 'hexwords', 'item4')][string]$Only = 'all'
)
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
. (Join-Path $root 'env\devshell.ps1') *> $null
$cxx = Join-Path $root 'toolchain\llvm-23.1.6\bin\clang++.exe'
if (-not (Test-Path $cxx)) { $cxx = 'clang++' }
$flags = @('-O3', '-DNDEBUG', '-std=gnu++23', '-msse4.1', '-march=x86-64-v3', '-fms-runtime-lib=dll',
  '-DNOMINMAX', '-DWIN32_LEAN_AND_MEAN', '-D_CRT_SECURE_NO_WARNINGS', '-fuse-ld=lld', '-Wall', '-Wextra')

function Get-LoadSnapshot {
  try {
    $total = (Get-CimInstance Win32_PerfFormattedData_PerfOS_Processor -Filter "Name='_Total'").PercentProcessorTime
    $top = Get-CimInstance Win32_PerfFormattedData_PerfProc_Process |
      Where-Object { $_.Name -notin @('_Total', 'Idle') -and $_.PercentProcessorTime -gt 0 } |
      Sort-Object PercentProcessorTime -Descending | Select-Object -First 8 |
      ForEach-Object { "$($_.Name)=$($_.PercentProcessorTime)%" }
    "total CPU $total% of $([Environment]::ProcessorCount) logical CPUs; busiest (per-CPU %): " + ($top -join ', ')
  } catch { "load snapshot unavailable: $_" }
}

function Invoke-Bench([string]$Name, [string]$Exe, [string]$ResultFile) {
  $benchArgs = @('--runs', "$Runs")
  if ($Quick) { $benchArgs += '--quick' }
  $header = "=== $Name  $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')  runs=$Runs quick=$([bool]$Quick)`nload before: $(Get-LoadSnapshot)"
  $output = & $Exe @benchArgs 2>&1 | Out-String
  $code = $LASTEXITCODE
  $text = "$header`n$output" + "load after: $(Get-LoadSnapshot)`nexit code: $code`n"
  Add-Content -LiteralPath $ResultFile -Value $text -Encoding UTF8
  Write-Host $text
  return $code
}

$failed = 0

if ($Only -in @('all', 'journal')) {
  $out = Join-Path $root 'build\agent8\journal'
  New-Item -ItemType Directory -Force $out | Out-Null
  & $cxx @flags "-I$root\DimensionsRecomp\rexlego\src" "-I$PSScriptRoot\journal" `
    "$PSScriptRoot\journal\journal_bench.cpp" -o "$out\journal_bench.exe"
  if ($LASTEXITCODE) { throw 'journal_bench build failed' }
  if (-not $NoRun) {
    if ((Invoke-Bench 'journal_bench' "$out\journal_bench.exe" "$PSScriptRoot\journal\results.txt") -ne 0) { $failed++ }
  }
}

if ($Only -in @('all', 'hexwords')) {
  $out = Join-Path $root 'build\agent8\hexwords'
  New-Item -ItemType Directory -Force $out | Out-Null
  function Get-HexWordsSource([string]$Path) {
    $lines = [IO.File]::ReadAllLines($Path)
    $start = [Array]::FindIndex($lines, [Predicate[string]] { param($l) $l -match '^std::string HexWords\(' })
    $end = [Array]::FindIndex($lines, [Predicate[string]] { param($l) $l -match '^void LogSkin\(' })
    if ($start -lt 0 -or $end -le $start) { throw "HexWords not found in $Path" }
    ($lines[$start..($end - 1)] -join "`n")
  }
  $oldSource = Get-HexWordsSource (Join-Path $root 'build\agent8\orig\native_skin_diagnostics.cpp')
  $newSource = Get-HexWordsSource (Join-Path $root 'DimensionsRecomp\rexlego\src\native_skin_diagnostics.cpp')
  $header = @"
#pragma once
// Generated by bench/agent8/build-journal-hexwords.ps1. Do not edit.
//   old_impl: build/agent8/orig/native_skin_diagnostics.cpp (session 1)
//   new_impl: DimensionsRecomp/rexlego/src/native_skin_diagnostics.cpp
#include <algorithm>
#include <cstdint>
#include <iomanip>
#include <sstream>
#include <string>
namespace old_impl {
$oldSource
}  // namespace old_impl
namespace new_impl {
$newSource
}  // namespace new_impl
"@
  [IO.File]::WriteAllText((Join-Path $out 'hexwords_extracted.h'), $header, (New-Object Text.UTF8Encoding $false))
  & $cxx @flags "-I$out" "$PSScriptRoot\hexwords\hexwords_bench.cpp" -o "$out\hexwords_bench.exe"
  if ($LASTEXITCODE) { throw 'hexwords_bench build failed' }
  if (-not $NoRun) {
    if ((Invoke-Bench 'hexwords_bench' "$out\hexwords_bench.exe" "$PSScriptRoot\hexwords\results.txt") -ne 0) { $failed++ }
  }
}

if ($Only -in @('all', 'item4')) {
  $out = Join-Path $root 'build\agent8\item4'
  New-Item -ItemType Directory -Force $out | Out-Null
  & $cxx @flags "$PSScriptRoot\item4\item4_bench.cpp" -o "$out\item4_bench.exe"
  if ($LASTEXITCODE) { throw 'item4_bench build failed' }
  if (-not $NoRun) {
    if ((Invoke-Bench 'item4_bench' "$out\item4_bench.exe" "$PSScriptRoot\item4\results.txt") -ne 0) { $failed++ }
  }
}

if ($failed) { Write-Output "FAILED benches: $failed"; exit 1 }
Write-Output 'ALL PASS'
