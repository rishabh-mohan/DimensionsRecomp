#!/usr/bin/env python3
"""gen_gameplay_route.py - M3 gameplay task: writes the two input scripts of build/agent3/gameplay/.

  explore-route.txt   EXPLORE2 (Overseer 20:13): ONE visible exploration run (native). A boot gated on the game.log
                      front-end state markers (boot2: install prompt, intro, title, Updates panel + Store notice, main
                      menu, New Game -> slot 1 -> Confirm -> autosave -> Toypad picture -> the story; the path of the
                      manual run 20261125-204323), then S: the 3 figure prompts (answered by the prompt sidecar's --on
                      triggers, else the game's 120 s failsafe), O: 120 s of no input, P: skip probes (A, START, B,
                      hold Y), an A ladder, a tag re-place, W: a walk/fight probe loop.
                      (The first explore route's 'vortex' (orange FF 6E 00) was the title screen's LED cycle.)
  gameplay-route.txt  the both-arms route: the same boot2 path and S prompts, then a shorter observe phase, the A-skip
                      probes, then a ~4 min walk/fight loop (M10 S1, m3-titlegate-rating: the old blind sleep 50 + one
                      START prefix is gone).

The walk/fight cycle comes from build/agent3/toypad/routes/level-l.txt (gen_route_l.py).
No route regex contains a comma (input.csv is comma separated). Marks named 'v-replace' make the toypad sidecar
(--then-mark v-replace --then-action replace) REMOVE and re-LOAD the 3 tags. Output is ASCII with CRLF.
Usage: python -B gen_gameplay_route.py [--check]   (--check: regenerate in memory and compare with the files; exit 1 if different)
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# EXPLORE2 title gate (boot2): settle s after the title marker, then TITLE_TRIES x (START + TITLE_WAIT s wait for 13);
# fixed bound 3 + 12 + 6 x ~10.8 = ~80 s, START tries at ~+15/26/37/47/58/69 s after 12
TITLE_SETTLE, TITLE_TRIES, TITLE_WAIT = 12, 6, 10

# stick values: XInput thumb, +Y = up/forward
N, S, E, W = (0, 30000), (0, -30000), (30000, 0), (-30000, 0)


def walk_cycle(L, c, dirs, shots=2):
    """one walk/fight cycle: 4 stick moves with attack/jump/build/camera between them; 'shots' marks."""
    (d1, d2, d3, d4) = dirs
    L += ["stick L %d %d 2000" % d1, "press X 3 150 250                               # attack x3"]
    L.append("mark w%02d-a" % c)
    L += ["stick L %d %d 2000" % d2, "press A                                         # jump"]
    L += ["stick L %d %d 2000" % d3, "hold B 1500                                     # build / use"]
    if shots > 1:
        L.append("mark w%02d-b" % c)
    L += ["stick L %d %d 2000" % d4, "stick R 20000 0 800                             # camera", "press X 2 150 250"]


def fe(state):
    """wait_log regex: the native front end settled in 'state' (krnl 'Native frontend transition' line, no pending)."""
    return '"current=%d pending=4294967295"' % state


def boot2(name, about):
    """EXPLORE2 boot (Overseer 20:13, R1): every front-end step gated on the game.log frontend-state marker instead of
    fixed sleeps. States from RUN-EXPLORE 20261125-195926 (fresh sandbox user): 7 install prompt (A; START does
    nothing), 0 install + intro (~184 s), 12 title (START; A/B do nothing), 13 'press A', 0 Updates panel
    (A = Store notice, then OK + B), 17 main menu (cursor on Credits), New Game -> 34/39/40 -> 47.
    wait_log scans forward from the previous match and has no branches: one wait per marker; a short wait that times
    out leaves the cursor at the end of the log, so the next wait still sees a later marker.
    Title gate (EXPLORE2 20261126-031601: one START 3.8 s after 12 was ignored, the title then sat 17 min; START/Enter
    was taken at +28.6, +53, +176 and +1067 s in other runs): a 12 s settle, then TITLE_TRIES x (START + a TITLE_WAIT s
    wait for 13). The runner cannot branch, so the later STARTs also run after a hit; START does nothing on the Updates
    panel (RUN-EXPLORE 20261125-195931 20:07:07) and at 13 it either does nothing or goes on to the Updates panel as A/B
    do. One B then converges both cases on the Updates panel (B at 13 -> 35/8/11/17/0, EXPLORE2 03:37:58; B does
    nothing on the Updates panel, manual 20261125-204323 20:48:19, or at the title). The Store-notice wait right after is
    the gate check: it can only match from the Updates panel, so its TIMEOUT means the title never took START."""
    L = ["# build/agent3/gameplay/%s - M3 gameplay task. Generated by gen_gameplay_route.py: do not edit by hand." % name]
    L += ["# " + s for s in about]
    L += [
        "# Needs the toypad sidecar (gameplay-run.ps1 starts it: the virtual Batman/Gandalf/Wyldstyle tags 2 s after the",
        "# front end's all-pads-white line; 'mark v-replace' = REMOVE + re-LOAD them). Every 'mark' = one screenshot.",
        "wait_first_frame 240",
        "mark first-frame",
        "wait_log %s 120                    # install prompt" % fe(7),
        "sleep 2",
        "mark install-prompt",
        "press A                                         # -> all pads white; the sidecar places the tags 2 s later",
        'wait_log "Toypad: pad 3 mode 1 lit FF FF FF" 25',
        "mark pads-white",
        'wait_log "Toypad listener: LOAD -> pad=3" 20',
        "mark tags-placed",
        "sleep 2",
    ]
    # install accept: A until state 0 (a match ends the ladder's purpose; the later short waits just time out)
    for i in range(1, 7):
        L += ["press A", "wait_log %s 6" % fe(0)]
    # Manual run 20261125-204323 (FE settled lines vs the key log): the intro ends by itself (12); START at 12 -> 13;
    # A at 13 -> 0 (Updates panel; hold B and BACK do nothing there); A -> the Store notice (5 -> 0); A = OK; B -> 17;
    # one short right tap moves the cursor Credits -> New Game; A -> 47 (save slots); A -> 49 (Confirm, default Yes);
    # A -> 52/53/54 (autosave notice, 53 + 54 come by themselves); A -> 55 (Toypad picture); A -> 0 = the story.
    L += ["mark intro-start",
          "sleep 20", "mark intro-20",
          "wait_log %s 420                  # title 'Press START' (the intro ends by itself)" % fe(12),
          "sleep 3", "mark title",
          "sleep %d                                        # title gate: settle (START at +3.8 s was ignored)" % TITLE_SETTLE]
    for k in range(1, TITLE_TRIES + 1):
        L += ["press START                                     # title gate try %d/%d" % (k, TITLE_TRIES),
              "wait_log %s %d" % (fe(13), TITLE_WAIT)]
    L += ["sleep 2", "mark press-start",
          "press B                                         # converge: 13 -> Updates panel; nothing if already there",
          "sleep 4", "mark updates-panel",
          "press A                                         # -> the Store notice (5 -> 0)",
          'wait_log "current=5 pending=0" 20               # TITLE GATE CHECK: TIMEOUT = the title never took START',
          "sleep 3", "mark store-notice",
          "press A                                         # OK",
          "sleep 3",
          "press B",
          "wait_log %s 20                  # main menu" % fe(17),
          "sleep 2", "mark main-menu",
          "stick L 30000 0 250                             # Credits -> New Game (one short tap)",
          "sleep 1.5", "mark menu-newgame",
          "press A",
          "wait_log %s 15                  # New Game: save slots" % fe(47),
          "sleep 3", "mark ng-slots",
          "press A                                         # slot 1",
          "wait_log %s 15                  # Confirm (default Yes)" % fe(49),
          "sleep 3", "mark ng-confirm",
          "press A",
          "wait_log %s 20                  # autosave notice (52 -> 53 -> 54)" % fe(54),
          "sleep 3", "mark ng-autosave",
          "press A",
          "wait_log %s 15                  # Toypad picture ('Select A')" % fe(55),
          "sleep 3", "mark ng-toypad",
          "press A",
          'wait_log "current=55 pending=0" 15              # -> the story (front end 0 from here)',
          "sleep 3", "mark story-00"]
    return L


def prompts(L):
    """S: one wait per story figure prompt; the prompt sidecar's --on triggers answer them (else the 120 s failsafe)."""
    L.append("# --- S: the story's figure prompts (manual run: pad 2 Batman, pad 3 Gandalf, pad 1 Wyldstyle; 120 s each) ---")
    for pad_, who in ((2, "batman"), (3, "gandalf"), (1, "wyldstyle")):
        L += ['wait_log "Toypad listener: LOAD -> pad=%d" 240' % pad_,
              "mark s-%s                                 # the sidecar answered (or the wait timed out)" % who,
              "sleep 10", "mark s-%s-10" % who]


def explore():
    L = boot2("explore-route.txt", [
        "EXPLORE2 (native): marker-gated boot -> title -> Updates -> main menu -> New Game -> slot 1 -> the story, then",
        "the 3 figure prompts (the prompt sidecar re-places / moves the asked tag; else the game's 120 s failsafe), then",
        "O = 120 s no input, skip probes, an A ladder, a tag re-place, a walk/fight loop. ~900 s; -Seconds 1500 (cap).",
        "No tp-* route marks: the prompts are the sidecar's job (--on); a timed-out wait jumps to the log end."])
    prompts(L)
    L.append("# --- O: observe, no input ---")
    for i in range(1, 13):
        L += ["sleep 10", "mark o-%02d" % i]
    L.append("# --- P: skip probes (one input, then a shot ~5 s later) ---")
    for name, step in [("p01-a", "press A"), ("p02-start", "press START"), ("p03-b", "press B"),
                       ("p04-hold-y", "hold Y 2000")]:
        L += [step, "sleep 5", "mark " + name]
    L.append("# --- L2: A ladder ---")
    for i in range(1, 9):
        L += ["press A", "sleep 6", "mark a-%02d" % i]
    L += ["mark v-replace                                  # sidecar: REMOVE + re-LOAD the 3 tags ~1 s later",
          "sleep 10", "mark r-01"]
    L.append("# --- W: walk/fight probe loop ---")
    rot = [(N, E, S, W), (E, S, W, N), (S, W, N, E), (W, N, E, S)]
    for c in range(1, 9):
        walk_cycle(L, c, rot[(c - 1) % 4])
    L += ["sleep 5", "mark end", "stop"]
    return L


def gameplay():
    L = boot2("gameplay-route.txt", [
        "Both-arms route: the EXPLORE2 marker-gated boot (title gate) -> New Game -> slot 1 -> the story, the 3 figure",
        "prompts (prompt sidecar), 60 s observe, the A/START-A skip probes, then ~4 min of walk/fight cycles (marks",
        "wNN-a/b). -Seconds 1500 per arm (a cap: the route's 'stop' ends it)."])
    prompts(L)
    L.append("# --- O: observe, no input ---")
    for i in range(1, 7):
        L += ["sleep 10", "mark o-%02d" % i]
    L += ["press A", "sleep 8", "mark s-a", "press START", "sleep 5", "press A", "sleep 8", "mark s-start-a",
          "mark in-level"]
    rot = [(N, E, S, W), (E, S, W, N), (S, W, N, E), (W, N, E, S)]
    for c in range(1, 19):
        walk_cycle(L, c, rot[(c - 1) % 4], shots=2 if c % 3 == 0 else 1)
    L += ["sleep 5", "mark end", "stop"]
    return L


def main():
    check = "--check" in sys.argv[1:]
    bad = 0
    for name, L in (("explore-route.txt", explore()), ("gameplay-route.txt", gameplay())):
        text = "\r\n".join(L) + "\r\n"
        text.encode("ascii")
        if any("," in s.split("#")[0] for s in L if s.startswith(("wait_log", "mark"))):
            print("FAIL %s: a comma in a wait_log/mark step" % name)
            bad += 1
        out = os.path.join(HERE, name)
        steps = sum(1 for s in L if s.strip() and not s.startswith("#"))
        marks = sum(1 for s in L if s.startswith("mark "))
        if check:
            same = os.path.exists(out) and open(out, "rb").read() == text.encode("ascii")
            print("%s %s (%d steps, %d marks)" % ("same" if same else "DIFFERENT", out, steps, marks))
            bad += 0 if same else 1
        else:
            with open(out, "wb") as f:
                f.write(text.encode("ascii"))
            print("wrote %s (%d steps, %d marks)" % (out, steps, marks))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
